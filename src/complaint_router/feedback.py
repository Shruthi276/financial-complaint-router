"""Encrypted storage of agent feedback (corrected routing labels).

Complaint text is personal data, so feedback records are encrypted at rest with
Fernet (AES-128-CBC + HMAC-SHA256). The key comes from ``FEEDBACK_ENCRYPTION_KEY``
(generated by ``make env``). The backend writes records; the preprocess stage
decrypts them and adds them to the training data.
"""

from __future__ import annotations

import json
import os
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
from cryptography.fernet import Fernet, InvalidToken

from complaint_router.categories import CATEGORY_KEYS
from complaint_router.logging_utils import get_logger
from complaint_router.text_cleaning import CLEAN_COLUMNS, normalize_text

logger = get_logger(__name__)
FEEDBACK_FILE = "feedback.enc.jsonl"


def _fernet() -> Fernet | None:
    key = os.environ.get("FEEDBACK_ENCRYPTION_KEY", "").strip()
    if not key:
        return None
    try:
        return Fernet(key.encode())
    except (ValueError, TypeError):
        logger.error("FEEDBACK_ENCRYPTION_KEY is not a valid Fernet key")
        return None


def append_feedback(directory: Path, record: dict) -> None:
    """Encrypt and append one feedback record.

    Raises:
        RuntimeError: if no valid encryption key is configured (we never store plaintext).
    """
    fernet = _fernet()
    if fernet is None:
        raise RuntimeError("Feedback storage disabled: FEEDBACK_ENCRYPTION_KEY not configured")
    record = {**record, "stored_at": datetime.now(timezone.utc).isoformat()}
    token = fernet.encrypt(json.dumps(record).encode()).decode()
    directory.mkdir(parents=True, exist_ok=True)
    with (directory / FEEDBACK_FILE).open("a", encoding="utf-8") as fh:
        fh.write(token + "\n")


def read_feedback(directory: Path) -> list[dict]:
    """Decrypt all feedback records (records that fail to decrypt are skipped)."""
    path = directory / FEEDBACK_FILE
    fernet = _fernet()
    if not path.exists() or fernet is None:
        return []
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        try:
            records.append(json.loads(fernet.decrypt(line.strip().encode())))
        except (InvalidToken, json.JSONDecodeError):
            logger.warning("Skipping undecryptable feedback record")
    return records


def load_feedback_examples(directory: Path) -> pd.DataFrame:
    """Convert feedback with a confirmed/corrected label into training rows."""
    rows = []
    for i, r in enumerate(read_feedback(directory)):
        label = r.get("correct_category")
        text = normalize_text(r.get("complaint_text", ""))
        if label not in CATEGORY_KEYS or len(text) < 20:
            continue
        rows.append({
            "complaint_id": f"feedback-{i}", "date_received": str(r.get("stored_at", ""))[:10],
            "text": text, "category": label,
            "priority": int(r.get("correct_priority") == "high"),
            "issue": "agent feedback", "company_response": "", "n_chars": len(text),
        })
    return pd.DataFrame(rows, columns=CLEAN_COLUMNS)
